// Test fixtures for the on-chain line of sight, produced by the site's own code (web/app/ephem.js + web/app/model.js):
// for each south-pole site and a spread of hours, the exact instruction inputs (quantized as the client sends them)
// and the site's answer (Earth elevation, azimuth, skyline, margin, in view). Writes tests/fixtures.rs.
// Run: node tools/los-onchain/gen-fixtures.mjs   (from the repository root)
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const root = new URL("../../", import.meta.url);
const ctx = { console, Math, Float32Array, Int32Array, Uint8Array, Map, Date, JSON };
ctx.window = ctx; ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of ["web/ephem_data.js", "web/sites_data.js", "web/app/ephem.js", "web/app/model.js"]) {
  vm.runInContext(readFileSync(new URL(f, root), "utf8"), ctx, { filename: f });
}
const { LunarEphem, Model, LUNAR_SITES } = ctx;
const sites = LUNAR_SITES.filter(s => s.terrain && s.horizon_deg && s.horizon_deg.length);
const hours = [0, 731, 2203, 4410, 6618, 8760, 10971, 13142, 15333, 17519];

const q = x => Math.round(x * 1e6);                    // µdeg, as the client encodes
const mdeg = x => Math.max(-32767, Math.min(32767, Math.round(x * 1000)));
let out = "// Generated by tools/los-onchain/gen-fixtures.mjs from web/app/ephem.js + web/app/model.js. Do not edit.\n";
out += "pub struct Site { pub name: &'static str, pub lat_ude: i32, pub lon_ude: i32, pub elev_m: i32, pub hz_mdeg: &'static [i16] }\n";
out += "pub struct Case { pub site: usize, pub hour: u32, pub elat_ude: i32, pub elon_ude: i32, pub edist_m: u32, pub el: f64, pub az: f64, pub sky: f64, pub visible: bool }\n";
out += "pub const SITES: &[Site] = &[\n";
for (const s of sites) {
  out += `  Site { name: ${JSON.stringify(s.name)}, lat_ude: ${q(s.lat)}, lon_ude: ${q(s.lon)}, elev_m: ${Math.round(s.elev_m || 0)}, hz_mdeg: &[${s.horizon_deg.map(mdeg).join(",")}] },\n`;
}
out += "];\npub const CASES: &[Case] = &[\n";
let n = 0, inView = 0;
sites.forEach((s, si) => {
  const m = Model.compute(s);
  for (const h of hours) {
    const sp = LunarEphem.subpoints(h);
    const a = LunarEphem.azel(s.lat, s.lon, h, s.elev_m || 0);
    const sky = a.earthEl - m.earM[h];                  // the skyline the site used at Earth's azimuth
    const vis = m.earUp[h] === 1;
    out += `  Case { site: ${si}, hour: ${h}, elat_ude: ${q(sp.earthLat)}, elon_ude: ${q(sp.earthLon)}, edist_m: ${Math.round(sp.earthDistKm * 1000)}, ` +
           `el: ${a.earthEl.toFixed(6)}, az: ${a.earthAz.toFixed(6)}, sky: ${sky.toFixed(6)}, visible: ${vis} },\n`;
    n++; if (vis) inView++;
  }
});
out += "];\n";
writeFileSync(new URL("tests/fixtures.rs", import.meta.url), out);
console.log(`fixtures: ${sites.length} sites, ${n} cases, ${inView} with Earth in view, ${n - inView} hidden`);
