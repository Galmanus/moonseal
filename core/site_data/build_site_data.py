# Build web/app/site-data.js: per-site values measured by NASA missions plus the IAU south-polar names, from public
# archives. Everything is reproducible with these commands (from the repository root):
#
#  1) LRO Diviner Polar Resource Product (PDS LRO-L-DLRE-5-PRP-V2.0, 605 MB ASCII), read around each site with HTTP
#     byte ranges (a few MB in total, never the whole table):
#     python3 -I core/site_data/prp_ranges.py "$SITES_ELEV" > /tmp/prp_sites.json
#  2) NASA GRAIL GRGM1200A free-air anomaly and error maps, degree 660 (PDS rsdmap), read with HTTP byte ranges:
#     python3 -I core/site_data/grail_sample.py "$SITES" > /tmp/grail_sites.json
#  3) USGS Gazetteer of Planetary Nomenclature, Moon centre points (public domain), unzipped in an empty directory:
#     curl -sLO https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/MOON_nomenclature_center_pts.zip
#  4) python3 -I core/site_data/build_site_data.py /tmp/prp_sites.json /tmp/grail_sites.json \
#       <dir>/MOON_nomenclature_center_pts.dbf web/app/site-data.js
# where SITES is the JSON {id: [lat, east_lon]} of the curated south-polar sites (web/sites_data.js) and SITES_ELEV
# the same with the LOLA elevation in metres as a third value.
import json, math, re, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dbf import read_dbf

prp_path, grail_path, dbf_path, out_path = sys.argv[1:5]
R = 1737.4
prp = json.load(open(prp_path))
grail = json.load(open(grail_path))

diviner = {}
for k, v in prp.items():
    c0, cells, trap = v['nearest'], v['within_1km'], v['cold_trap']
    tmax = [c['tmax'] for c in cells] or [c0['tmax']]
    diviner[k] = {
        'tmax_k': round(c0['tmax'], 1), 'tavg_k': round(c0['tavg'], 1), 'ice_depth_m': round(c0['ice'], 3),
        'cell_offset_m': round(c0['d'] * 1000), 'cell_size_m': 500,       # 1200 x 1200 grid, vertices about 0.499 km apart
        'tmax_1km_k': [round(min(tmax), 1), round(max(tmax), 1)], 'cells_1km': len(cells),
        'cold_trap_km': trap['km'] if trap else None,
        'cold_trap_tmax_k': round(trap['tmax'], 1) if trap else None,
        'cold_trap_searched_km': trap['searched_km'] if trap else None,
    }

grav = {k: {'anom_mgal': v['anom_mgal'], 'err_mgal': v['err_mgal']} for k, v in grail.items()}

names = []
for _, r in read_dbf(dbf_path):
    try:
        lat, lon = float(r['center_lat']), float(r['center_lon']) % 360
    except ValueError:
        continue
    if lat > -75 or r['approval'] != 'Adopted by IAU':
        continue
    fid = re.search(r'/Feature/(\d+)', r['link'])
    d = float(r['diameter']) if r['diameter'] else None
    names.append([r['name'], round(lat, 4), round(lon, 4), round(d, 2) if d else None, r['code'], int(fid.group(1)) if fid else None])
names.sort(key=lambda x: x[1])

js = ('/* moonseal: per-site values measured by NASA missions, and the IAU south-polar names, from public archives.\n'
      '   Generated by core/site_data/build_site_data.py (commands in its header); do not edit by hand.\n'
      '   diviner: LRO Diviner Polar Resource Product, PDS LRO-L-DLRE-5-PRP-V2.0 (Paige et al. 2010): mesh cell nearest the\n'
      '     site; tmax_k annual maximum at the surface, tavg_k annual average 2 cm down, ice_depth_m depth below which water\n'
      '     ice loses < 1 kg/m^2 per billion years (0 = stable at the surface, -999 = not stable in the top 2.8738 m);\n'
      '     cold_trap_km: distance to the nearest mesh cell where ice is stable at the surface.\n'
      '   grail: NASA GRAIL GRGM1200A free-air anomaly (and its error) expanded to degree 660, on a 1738.0 km reference\n'
      '     sphere, PDS rsdmap gggrx_1200a_anom_l660 / anomerr_l660, bilinear at the site (milligals; 1 mGal = 1e-5 m/s^2).\n'
      '   names: USGS Gazetteer of Planetary Nomenclature, Moon centre points, IAU-adopted, centre latitude <= 75 S:\n'
      '     [name, centre lat, centre east lon, diameter km, feature code, USGS feature id]. Public domain. */\n'
      'window.MOONSEAL_SITE_DATA = ' + json.dumps({'diviner': diviner, 'grail': grav, 'names': names},
                                                  ensure_ascii=False, separators=(',', ':')) + ';\n')
open(out_path, 'w', encoding='utf-8').write(js)
print('wrote', out_path, len(js.encode('utf-8')), 'bytes;', len(diviner), 'Diviner sites,', len(grav), 'GRAIL sites,', len(names), 'names')
